class ConversionError(ValueError):
    def __init__(self, code, message, **context):
        self.code, self.context = code, context
        super().__init__(message)


def fail(code, message, **context):
    raise ConversionError(code, message, **context)


def children(shape):
    it = TopoDS_Iterator(shape, False, False)
    while it.More():
        yield it.Value()
        it.Next()


def read_step(path):
    reader = STEPControl_Reader()
    status = reader.ReadFile(str(path))
    if status != IFSelect_RetDone:
        fail("STEP_READ_FAILED", str(status))
    reader.SetSystemLengthUnit(1.0)
    roots = reader.NbRootsForTransfer()
    if roots <= 0:
        fail("NO_TRANSFER_ROOTS", "No transferable roots")
    transfers = []
    for index in range(1, roots + 1):
        ok = reader.TransferRoot(index)
        transfers.append({"root": index, "transferred": bool(ok)})
        if not ok:
            fail("STEP_TRANSFER_FAILED", "Root transfer failed", root=index)
    shape = reader.OneShape()
    if shape.IsNull():
        fail("EMPTY_BASELINE", "Imported shape is null")
    if not BRepCheck_Analyzer(shape, True).IsValid():
        fail("SOURCE_BREP_INVALID", "BRepCheck_Analyzer rejected imported baseline")
    ex = TopExp_Explorer(shape, TopAbs_SOLID)
    if not ex.More():
        fail("NO_SOLID", "Profile requires solid geometry")
    return shape, {"roots": transfers, "target_unit": "mm", "reader": "STEPControl_Reader",
                   "product_assembly_preserved": False,
                   "import_configuration": "fresh process, OCCT defaults except target unit=mm",
                   "import_warning_coverage": "native stdout/stderr; not all warnings classified"}


