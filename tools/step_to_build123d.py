class Generator:
    def __init__(self, shape, policy):
        self.root, self.policy = shape, policy
        self.map = TopTools_IndexedMapOfShape()
        self.nodes, self.lines, self.changes = [], [], []
        self.geometries = {}
        self.count_types = {}
        self.visit(shape)

    def canonical(self, shape):
        return shape.Located(TopLoc_Location()).Oriented(TopAbs_FORWARD)

    def visit(self, shape):
        canonical = self.canonical(shape)
        existing = self.map.FindIndex(canonical)
        if existing:
            return existing - 1
        index = self.map.Add(canonical) - 1
        self.nodes.append(canonical)
        if canonical.Locked():
            fail("UNSUPPORTED_LOCKED_SHAPE", "Locked source definition", node=index)
        for child in children(canonical):
            self.visit(child)
        return index

    def idx(self, shape):
        return self.map.FindIndex(self.canonical(shape)) - 1

    def emit(self, text):
        self.lines.append(text)

    def number(self, value):
        value = float(value)
        if not math.isfinite(value):
            fail("NONFINITE_GEOMETRY", "Non-finite constructor parameter")
        return repr(value)

    def point(self, value):
        vals = [value.X(), value.Y()]
        if hasattr(value, "Z"):
            vals.append(value.Z())
        return ("gp_Pnt" if len(vals) == 3 else "gp_Pnt2d") + "(" + ", ".join(map(self.number, vals)) + ")"

    def direction(self, value):
        vals = [value.X(), value.Y()]
        if hasattr(value, "Z"):
            vals.append(value.Z())
        return ("gp_Dir" if len(vals) == 3 else "gp_Dir2d") + "(" + ", ".join(map(self.number, vals)) + ")"

    def axis(self, axis):
        name = type(axis).__name__
        if name == "gp_Ax1":
            return f"gp_Ax1({self.point(axis.Location())}, {self.direction(axis.Direction())})"
        if name in {"gp_Ax2d", "gp_Ax22d"}:
            args = [self.point(axis.Location()), self.direction(axis.XDirection() if name == "gp_Ax22d" else axis.Direction())]
            if name == "gp_Ax22d":
                args.append(self.direction(axis.YDirection()))
            return f"{name}({', '.join(args)})"
        args = [self.point(axis.Location()), self.direction(axis.Direction()), self.direction(axis.XDirection())]
        expression = f"{name}({', '.join(args)})"
        if name == "gp_Ax3" and not axis.Direct():
            var = f"ax{len(self.lines)}"
            self.emit(f"{var} = {expression}")
            self.emit(f"{var}.YReverse()")
            return var
        return expression

    def loc(self, loc):
        if loc.IsIdentity():
            return "TopLoc_Location()"
        t = loc.Transformation()
        if abs(t.ScaleFactor() - 1.0) > 1e-12 or t.IsNegative():
            fail("UNSUPPORTED_TRANSFORM", "Only proper rigid locations supported")
        return f"location({[t.Value(i,j) for i in range(1,4) for j in range(1,5)]!r})"

    def occurrence(self, shape):
        ori = shape.Orientation()
        if ori not in (TopAbs_FORWARD, TopAbs_REVERSED):
            fail("UNSUPPORTED_ORIENTATION", str(ori))
        orientation = "TopAbs_FORWARD" if ori == TopAbs_FORWARD else "TopAbs_REVERSED"
        return f"use(n{self.idx(shape)}, {orientation}, {self.loc(shape.Location())})"

    def a1(self, cls, values):
        return f"array1({cls}, [{', '.join(values)}])"

    def geometry(self, obj):
        if obj is None:
            fail("MISSING_GEOMETRY", "Null geometry handle")
        if obj in self.geometries:
            return self.geometries[obj]
        typ = type(obj).__name__
        self.count_types[typ] = self.count_types.get(typ, 0) + 1
        var = f"g{len(self.geometries)}"
        self.geometries[obj] = var
        args = []
        dim = 2 if typ.startswith("Geom2d_") else 3
        if typ in {"Geom_Line", "Geom2d_Line"}:
            line = obj.Lin() if dim == 3 else obj.Lin2d()
            args = [self.point(line.Location()), self.direction(line.Direction())]
        elif typ in {"Geom_Circle", "Geom2d_Circle", "Geom_Ellipse", "Geom2d_Ellipse",
                     "Geom_Hyperbola", "Geom2d_Hyperbola", "Geom_Parabola", "Geom2d_Parabola"}:
            axis = obj.Position()
            args = [self.axis(axis)]
            if "Circle" in typ:
                args.append(self.number(obj.Radius()))
            elif "Parabola" in typ:
                args.append(self.number(obj.Focal()))
            else:
                args += [self.number(obj.MajorRadius()), self.number(obj.MinorRadius())]
        elif typ in {"Geom_Plane", "Geom_CylindricalSurface", "Geom_ConicalSurface",
                     "Geom_SphericalSurface", "Geom_ToroidalSurface"}:
            args = [self.axis(obj.Position())]
            if typ == "Geom_ConicalSurface":
                args += [self.number(obj.SemiAngle()), self.number(obj.RefRadius())]
            elif typ == "Geom_ToroidalSurface":
                args += [self.number(obj.MajorRadius()), self.number(obj.MinorRadius())]
            elif typ != "Geom_Plane":
                args.append(self.number(obj.Radius()))
        elif typ in {"Geom_BSplineCurve", "Geom2d_BSplineCurve", "Geom_BezierCurve", "Geom2d_BezierCurve"}:
            args = [self.a1("Array1_gp_Pnt" if dim == 3 else "Array1_gp_Pnt2d",
                            [self.point(obj.Pole(i)) for i in range(1, obj.NbPoles()+1)])]
            if obj.IsRational():
                args.append(self.a1("Array1_double", [self.number(obj.Weight(i)) for i in range(1,obj.NbPoles()+1)]))
            if "BSpline" in typ:
                args += [self.a1("Array1_double", [self.number(obj.Knot(i)) for i in range(1,obj.NbKnots()+1)]),
                         self.a1("Array1_int", [str(obj.Multiplicity(i)) for i in range(1,obj.NbKnots()+1)]),
                         str(obj.Degree()), repr(obj.IsPeriodic())]
        elif typ in {"Geom_BSplineSurface", "Geom_BezierSurface"}:
            rows = ["[" + ", ".join(self.point(obj.Pole(i,j)) for j in range(1,obj.NbVPoles()+1)) + "]"
                    for i in range(1,obj.NbUPoles()+1)]
            args = [f"array2(Array2_gp_Pnt, [{', '.join(rows)}])"]
            if obj.IsURational() or obj.IsVRational():
                rows = ["[" + ", ".join(self.number(obj.Weight(i,j)) for j in range(1,obj.NbVPoles()+1)) + "]"
                        for i in range(1,obj.NbUPoles()+1)]
                args.append(f"array2(Array2_double, [{', '.join(rows)}])")
            if "BSpline" in typ:
                for axis in ("U", "V"):
                    args.append(self.a1("Array1_double", [self.number(getattr(obj,axis+"Knot")(i))
                                for i in range(1,getattr(obj,"Nb"+axis+"Knots")()+1)]))
                for axis in ("U", "V"):
                    args.append(self.a1("Array1_int", [str(getattr(obj,axis+"Multiplicity")(i))
                                for i in range(1,getattr(obj,"Nb"+axis+"Knots")()+1)]))
                args += [str(obj.UDegree()), str(obj.VDegree()), repr(obj.IsUPeriodic()), repr(obj.IsVPeriodic())]
        elif typ in {"Geom_TrimmedCurve", "Geom2d_TrimmedCurve"}:
            args = [self.geometry(obj.BasisCurve()), self.number(obj.FirstParameter()), self.number(obj.LastParameter()), "True", "False"]
        elif typ == "Geom_SurfaceOfLinearExtrusion":
            args = [self.geometry(obj.BasisCurve()), self.direction(obj.Direction())]
        elif typ == "Geom_SurfaceOfRevolution":
            args = [self.geometry(obj.BasisCurve()), self.axis(obj.Axis())]
        elif typ == "Geom_RectangularTrimmedSurface":
            args = [self.geometry(obj.BasisSurface())] + [self.number(v) for v in obj.Bounds()]
        elif typ == "Geom_OffsetSurface":
            # Retain the analytic offset representation. Keep OCCT's C0 checks
            # enabled; unsupported continuity is an explicit construction failure.
            args = [self.geometry(obj.BasisSurface()), self.number(obj.Offset()), "False"]
        else:
            fail("UNSUPPORTED_GEOMETRY", f"No validated constructor template for {typ}", geometry_type=typ)
        self.emit(f"{var} = {typ}({', '.join(args)})")
        return var

    def generate(self):
        if self.policy == "length_grid_0p5_mm":
            return self.generate_grid()
        # Phase 1: vertices, edges (without children), and surfaces/faces.
        for i, node in enumerate(self.nodes):
            typ = node.ShapeType().name.replace("TopAbs_", "").title().replace("Compsolid", "CompSolid")
            self.emit(f"n{i} = TopoDS_{typ}()")
            if typ == "Vertex":
                self.emit(f"b.MakeVertex(n{i}, {self.point(BRep_Tool.Pnt_s(TopoDS.Vertex(node)))}, {BRep_Tool.Tolerance_s(TopoDS.Vertex(node))!r})")
            elif typ == "Edge":
                edge = TopoDS.Edge(node)
                self.emit(f"b.MakeEdge(n{i})")
                loc = TopLoc_Location()
                curve = BRep_Tool.Curve_s(edge, loc, 0., 0.)
                if curve is not None:
                    self.emit(f"b.UpdateEdge(n{i}, {self.geometry(curve)}, {self.loc(loc)}, {BRep_Tool.Tolerance_s(edge)!r})")
                elif not BRep_Tool.Degenerated_s(edge):
                    fail("UNSUPPORTED_CURVE_REPRESENTATION", "Non-degenerate edge has no 3D curve", node=i)
                lo, hi = BRep_Tool.Range_s(edge)
                self.emit(f"b.Range(n{i}, {lo!r}, {hi!r}, True)")
                self.emit(f"b.Degenerated(n{i}, {BRep_Tool.Degenerated_s(edge)!r})")
            elif typ == "Face":
                face = TopoDS.Face(node)
                loc = TopLoc_Location()
                surf = BRep_Tool.Surface_s(face, loc)
                self.emit(f"b.MakeFace(n{i}, {self.geometry(surf)}, {self.loc(loc)}, {BRep_Tool.Tolerance_s(face)!r})")
                self.emit(f"b.NaturalRestriction(n{i}, {BRep_Tool.NaturalRestriction_s(face)!r})")
            elif typ in {"Wire", "Shell", "Solid", "CompSolid", "Compound"}:
                self.emit(f"b.Make{typ}(n{i})")
            else:
                fail("UNSUPPORTED_TOPOLOGY", typ, node=i)
        # Edge vertex occurrences and parameters before adding containers.
        for i, node in enumerate(self.nodes):
            if node.ShapeType().name == "TopAbs_EDGE":
                edge = TopoDS.Edge(node)
                for child in children(edge):
                    v = TopoDS.Vertex(child)
                    expr = f"TopoDS.Vertex({self.occurrence(v)})"
                    self.emit(f"b.Add(n{i}, {expr})")
                    param = BRep_Tool.Parameter_s(v, edge)
                    self.emit(f"b.UpdateVertex({expr}, {param!r}, n{i}, {BRep_Tool.Tolerance_s(v)!r})")
        # Explicit pcurves: plane projections may be materialized by OCCT.
        for fi, node in enumerate(self.nodes):
            if node.ShapeType().name != "TopAbs_FACE":
                continue
            face = TopoDS.Face(node)
            seen = set()
            exp = TopExp_Explorer(face, __import__('OCP.TopAbs', fromlist=['TopAbs_EDGE']).TopAbs_EDGE)
            while exp.More():
                edge = TopoDS.Edge(exp.Current().Oriented(TopAbs_FORWARD))
                ei = self.idx(edge)
                key = (ei, tuple(edge.Location().Transformation().Value(i,j) for i in range(1,4) for j in range(1,5)))
                if key not in seen:
                    seen.add(key)
                    eexpr = f"TopoDS.Edge({self.occurrence(edge)})"
                    pc = BRep_Tool.CurveOnSurface_s(edge, face, 0., 0.)
                    if pc is None:
                        fail("MISSING_PCURVE", "No edge-face pcurve", edge=ei, face=fi)
                    args = [self.geometry(pc)]
                    if BRep_Tool.IsClosed_s(edge, face):
                        pc2 = BRep_Tool.CurveOnSurface_s(TopoDS.Edge(edge.Reversed()), face, 0., 0.)
                        if pc2 is None:
                            fail("MISSING_SEAM_PCURVE", "Missing second seam pcurve", edge=ei, face=fi)
                        args.append(self.geometry(pc2))
                    self.emit(f"b.UpdateEdge({eexpr}, {', '.join(args)}, n{fi}, {BRep_Tool.Tolerance_s(edge)!r})")
                    lo, hi = BRep_Tool.Range_s(edge, face)
                    self.emit(f"b.Range({eexpr}, n{fi}, {lo!r}, {hi!r})")
                exp.Next()
        for i in reversed(range(len(self.nodes))):
            node = self.nodes[i]
            if node.ShapeType().name not in {"TopAbs_VERTEX", "TopAbs_EDGE"}:
                for child in children(node):
                    self.emit(f"b.Add(n{i}, {self.occurrence(child)})")
            if node.ShapeType().name == "TopAbs_EDGE":
                edge = TopoDS.Edge(node)
                self.emit(f"b.SameRange(n{i}, {BRep_Tool.SameRange_s(edge)!r})")
                self.emit(f"b.SameParameter(n{i}, {BRep_Tool.SameParameter_s(edge)!r})")
            self.emit(f"n{i}.Closed({node.Closed()!r})")
        return self.finish()

    def generate_grid(self):
        # A defined independent/derived-field template: vertex xyz and placement
        # translations are independent; lines, planes and UVs are derived.
        # First version deliberately rejects curved surfaces and placed definitions.
        for i, node in enumerate(self.nodes):
            for child in children(node):
                if not child.Location().IsIdentity():
                    fail("QUANTIZATION_RECONSTRUCTION_UNSUPPORTED", "Grid template requires identity child locations", node=i)
            if node.ShapeType().name == "TopAbs_FACE":
                surf = BRep_Tool.Surface_s(TopoDS.Face(node))
                if type(surf).__name__ != "Geom_Plane":
                    fail("QUANTIZATION_RECONSTRUCTION_UNSUPPORTED", "Grid template currently supports planar polyhedra only",
                         node=i, geometry_type=type(surf).__name__)
            if node.ShapeType().name == "TopAbs_EDGE":
                e = TopoDS.Edge(node)
                curve = BRep_Tool.Curve_s(e, 0., 0.)
                if curve is None or type(curve).__name__ != "Geom_Line" or BRep_Tool.Degenerated_s(e):
                    fail("QUANTIZATION_RECONSTRUCTION_UNSUPPORTED", "Grid template requires non-degenerate straight edges",
                         node=i, geometry_type=type(curve).__name__)
        if not self.root.Location().IsIdentity():
            fail("QUANTIZATION_RECONSTRUCTION_UNSUPPORTED", "Grid template requires identity root location")
        self.emit("from OCP.BRepBuilderAPI import BRepBuilderAPI_MakeEdge")
        points = {}
        for i, node in enumerate(self.nodes):
            if node.ShapeType().name == "TopAbs_VERTEX":
                p = BRep_Tool.Pnt_s(TopoDS.Vertex(node))
                coords = []
                for axis, value in zip("xyz", (p.X(),p.Y(),p.Z())):
                    rec = quantize_parameter(value, object_id=f"n{i}", field=f"point.{axis}",
                            field_kind="point_coordinate", unit="mm", coordinate_space="definition_local")
                    self.changes.append(rec)
                    coords.append(float(rec['after']))
                points[i] = coords
                self.emit(f"n{i} = TopoDS_Vertex()")
                self.emit(f"b.MakeVertex(n{i}, gp_Pnt{tuple(coords)!r}, {BRep_Tool.Tolerance_s(TopoDS.Vertex(node))!r})")
        for i, node in enumerate(self.nodes):
            if node.ShapeType().name == "TopAbs_EDGE":
                cc = list(children(node))
                if len(cc) != 2 or {c.Orientation() for c in cc} != {TopAbs_FORWARD,TopAbs_REVERSED}:
                    fail("QUANTIZATION_RECONSTRUCTION_UNSUPPORTED", "Expected two ordinary oriented endpoints", node=i)
                start = next(c for c in cc if c.Orientation() == TopAbs_FORWARD)
                end = next(c for c in cc if c.Orientation() == TopAbs_REVERSED)
                if math.dist(points[self.idx(start)], points[self.idx(end)]) <= 1e-9:
                    fail("QUANTIZATION_FEATURE_COLLAPSE", "Edge endpoints collapse on 0.5 mm grid", node=i)
                self.emit(f"n{i} = BRepBuilderAPI_MakeEdge(n{self.idx(start)}, n{self.idx(end)}).Edge()")
        # Derive each face plane with original normal orientation; reject nonplanarity.
        import numpy as np
        from OCP.TopAbs import TopAbs_VERTEX
        for i, node in enumerate(self.nodes):
            if node.ShapeType().name != "TopAbs_FACE":
                continue
            ids = set()
            ex = TopExp_Explorer(node, TopAbs_VERTEX)
            while ex.More():
                ids.add(self.idx(ex.Current())); ex.Next()
            xyz = np.array([points[j] for j in sorted(ids)])
            if len(xyz) < 3:
                fail("QUANTIZATION_FEATURE_COLLAPSE", "Face has fewer than three vertices", node=i)
            center = xyz.mean(axis=0)
            _, singular, vh = np.linalg.svd(xyz-center, full_matrices=False)
            if singular[1] < 1e-9:
                fail("QUANTIZATION_FEATURE_COLLAPSE", "Face collapsed to line", node=i)
            normal = vh[-1]
            deviation = float(np.max(np.abs((xyz-center) @ normal)))
            if deviation > 1e-7:
                fail("QUANTIZATION_CONSTRAINT_CONFLICT", "Quantized vertices are no longer coplanar", node=i, deviation_mm=deviation)
            old = BRep_Tool.Surface_s(TopoDS.Face(node)).Position()
            if float(normal @ np.array([old.Direction().X(),old.Direction().Y(),old.Direction().Z()])) < 0:
                normal = -normal
            self.emit(f"n{i} = TopoDS_Face()")
            self.emit(f"b.MakeFace(n{i}, Geom_Plane(gp_Pnt{tuple(map(float,center))!r}, gp_Dir{tuple(map(float,normal))!r}), {BRep_Tool.Tolerance_s(TopoDS.Face(node))!r})")
            self.emit(f"b.NaturalRestriction(n{i}, False)")
        for i, node in enumerate(self.nodes):
            typ = node.ShapeType().name.replace('TopAbs_', '').title().replace("Compsolid", "CompSolid")
            if typ not in {'Vertex','Edge','Face'}:
                self.emit(f"n{i} = TopoDS_{typ}()")
                self.emit(f"b.Make{typ}(n{i})")
        for i in reversed(range(len(self.nodes))):
            if self.nodes[i].ShapeType().name not in {'TopAbs_VERTEX','TopAbs_EDGE'}:
                for child in children(self.nodes[i]):
                    self.emit(f"b.Add(n{i}, {self.occurrence(child)})")
            self.emit(f"n{i}.Closed({self.nodes[i].Closed()!r})")
        return self.finish()

    def finish(self):
        self.emit(f"root = {self.occurrence(self.root)}")
        self.emit("if not BRepCheck_Analyzer(root, True).IsValid():")
        self.emit("    invalid_nodes = []")
        self.emit("    for node_id, node in [" + ', '.join(f"('n{i}', n{i})" for i in range(len(self.nodes))) + "]:")
        self.emit("        if not BRepCheck_Analyzer(node, True).IsValid():")
        self.emit("            invalid_nodes.append((node_id, str(node.ShapeType())))")
        self.emit("    raise ValueError('REBUILT_BREP_INVALID: invalid nodes=' + repr(invalid_nodes))")
        self.emit("return Shape.cast(root)")
        return RUNTIME + f"POLICY = {self.policy!r}\n\ndef build_model():\n    b = BRep_Builder()\n" + ''.join('    '+s+'\n' for s in self.lines) + "\nresult = build_model()\n\nif __name__ == '__main__':\n    print('Valid=', result.is_valid, '; solids=', len(result.solids()), '; volume=', result.volume)\n"


def convert(source, output, policy):
    source, output = Path(source).resolve(), Path(output).resolve()
    if source == output or output.suffix.lower() != '.py':
        fail("INVALID_OUTPUT_PATH", "Output must be a separate .py path")
    shape, metadata = read_step(source)
    generator = Generator(shape, policy)
    code = generator.generate()
    compile(code, str(output), 'exec')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(code, encoding='utf-8')
    return {"source": str(source), "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "output": str(output), "generator_version": VERSION, "policy": policy,
            "status": "code_generated_unverified", "import": metadata,
            "geometry_types": generator.count_types, "definition_count": len(generator.nodes),
            "quantization_records": generator.changes}


